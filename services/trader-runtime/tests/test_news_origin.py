"""原始来源识别规则（news_origin）：常见说法认得出，外国同名机构、裸词与预期类说法不误认。"""
from __future__ import annotations

import pytest

from trader_runtime.news_origin import origins_of, retells


@pytest.mark.parametrize(("text", "origin"), [
    ("据新华社报道，国务院常务会议研究部署稳就业举措", "新华社"),
    ("新华社北京10月13日电 国家主席习近平13日下午同博茨瓦纳总统举行会谈", "新华社"),
    ("10月13日下午，国家主席习近平在北京人民大会堂同博科举行会谈。（新华社）", "新华社"),
    ("据央视新闻，伊朗称美国已接受伊方所提部分条件", "央视新闻"),
    ("海关总署公布，前9个月我国货物贸易进出口总值同比增长", "海关总署"),
    ("海关总署10月13日发布数据显示，9月进口铁矿砂1.1亿吨", "海关总署"),
    ("国家统计局数据显示，2026年9月份全国居民消费价格同比上涨0.4%", "国家统计局"),
    ("据国家统计局，9月PPI同比下降2.3%", "国家统计局"),
    ("中国人民银行公告，今日开展1000亿元7天期逆回购操作", "中国人民银行"),
    ("国家发改委：将进一步加大对民间投资的支持", "国家发改委"),
    ("发改委：四季度将加快推进重大项目", "国家发改委"),
    ("商务部新闻发言人表示，将对原产于美国的进口丙烷征收反倾销税", "商务部"),
    ("农业农村部数据显示，9月能繁母猪存栏环比下降", "农业农村部"),
    ("上期所发布通知，调整燃料油期货相关合约交易限额", "上期所"),
    ("郑州商品交易所公告，自10月14日起调整棉花期货交易手续费", "郑商所"),
    ("大商所：铁矿石期货合约交易保证金比例调整为12%", "大商所"),
    ("据路透社报道，OPEC+考虑12月起继续增产", "路透"),
    ("彭博援引知情人士称，智利铜矿罢工持续", "彭博"),
])
def test_common_attributions_name_their_original_source(text: str, origin: str) -> None:
    assert origin in origins_of(text)


@pytest.mark.parametrize("text", [
    "美国劳工统计局数据显示，9月非农就业新增25万人",  # 不是国家统计局
    "韩国海关数据显示，10月前10天出口同比增长",  # 不是海关总署
    "欧洲央行公布的数据显示，隔夜存款规模小幅回落",  # 不是中国人民银行
    "美国商务部表示，将对进口铜加征关税",  # 外国同名部委
    "美国财政部公布，9月预算赤字收窄",
    "香港证监会对涉嫌操纵首次公开招股的集团采取行动",
    "新华社区卫生服务中心开展义诊",  # 新华社区 ≠ 新华社
    "市场等待国家统计局数据，期价窄幅震荡",  # 预期，不是出处
    "浙江省发改委：推进重大项目建设",  # 省发改委不是国家发改委
    "铜价上涨，沪铜主力合约收涨1.2%",
])
def test_lookalikes_and_bare_words_are_not_attributed(text: str) -> None:
    assert origins_of(text) == []


def test_a_report_with_several_attributions_names_each_once() -> None:
    assert origins_of("据新华社报道，海关总署公布前9个月进出口数据，国家统计局同日发布") == ["新华社", "国家统计局", "海关总署"]  # 规则表顺序


def test_retells_needs_most_of_the_official_title_in_the_report() -> None:
    official = "2026年9月份居民消费价格同比上涨0.4%"
    assert retells(official, "国家统计局：9月份居民消费价格同比上涨0.4%",
                   "国家统计局数据显示，2026年9月份，全国居民消费价格同比上涨0.4%。其中，城市上涨0.4%")
    # 改写过的说法不硬并：只标原始来源。
    assert not retells(official, "统计局：9月CPI同比涨0.4%", "国家统计局：9月CPI同比上涨0.4%，核心CPI上涨0.8%")
    assert retells("关于调整燃料油、石油沥青期货相关合约交易限额的通知", "上期所调整交易限额",
                   "上期所发布通知，调整燃料油、石油沥青期货相关合约交易限额，自10月12日起执行")
    assert retells("关于调整铜期货交易保证金的通知", "上期所：关于调整铜期货交易保证金的通知！", "")
    assert not retells("通知", "上期所发布通知", "")  # 太短的官方标题不拿来比


@pytest.mark.parametrize(("official", "title", "opening"), [
    # 同一模板、换了品种（#854）：14 个字对里 12 个相同，仍是两条通知。
    ("关于调整铜期货交易保证金的通知", "关于调整铝期货交易保证金的通知", "上期所发布通知，调整铝期货交易保证金，自即日起执行"),
    # 同品种不同合约、不同数值、不同生效日、不同节假日。
    ("关于cu2512合约交易限额调整的通知", "上期所：关于cu2601合约交易限额调整的通知", ""),
    ("关于调整螺纹钢期货交易手续费为成交金额万分之一的通知", "上期所：关于调整螺纹钢期货交易手续费为成交金额万分之二的通知", ""),
    ("关于自2026年10月15日起调整铜期货交易保证金的通知", "上期所：关于自2026年10月16日起调整铜期货交易保证金的通知", ""),
    ("关于2026年国庆节期间调整各品种交易保证金的通知", "上期所：关于2026年春节期间调整各品种交易保证金的通知", ""),
    # 官方标题里的数字转载里没有：不算照着说。
    ("关于调整cu2512合约交易保证金的通知", "上期所：关于调整合约交易保证金的通知", ""),
])
def test_a_same_template_notice_about_something_else_is_not_a_retelling(official, title, opening) -> None:
    assert not retells(official, title, opening)
